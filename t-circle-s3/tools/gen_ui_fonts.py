#!/usr/bin/env python3
"""Rasterize Inter into 4-bit glyph tables for the round screen's text cards.

Inter (SIL Open Font License) is the font the Comma apps use; the variable TTF in
reference/fonts/ is a copy of comma-android's res/font/inter_variable.ttf.

Output:
  main/ui_font.c, main/ui_font.h  two fonts (ui_font_small: printable ASCII,
                                  ui_font_large: digits and a few symbols)

Each glyph is a tight bitmap of 4-bit coverage, two pixels per byte, high nibble left,
rows padded to whole bytes.

Needs: pip install pillow
"""

import pathlib

from PIL import Image, ImageDraw, ImageFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
TTF = ROOT / "reference" / "fonts" / "Inter-Variable.ttf"

FONTS = [
    # name, px, weight, characters
    ("small", 14, 500, [chr(c) for c in range(32, 127)]),
    ("large", 36, 600, list(" 0123456789")),
]


def load(px, weight):
    font = ImageFont.truetype(str(TTF), px)
    axes = font.get_variation_axes()
    values = []
    for axis in axes:
        name = axis["name"].decode() if isinstance(axis["name"], bytes) else axis["name"]
        if name == "Weight":
            values.append(weight)
        elif name == "Optical size":
            values.append(max(axis["minimum"], min(axis["maximum"], px)))
        else:
            values.append(axis["default"])
    font.set_variation_by_axes(values)
    return font


def rasterize(font, ch):
    ascent, _ = font.getmetrics()
    left, top, right, bottom = font.getbbox(ch)
    advance = round(font.getlength(ch))
    if right <= left or bottom <= top:
        return dict(w=0, h=0, x=0, y=0, adv=advance, data=b"")
    w, h = right - left, bottom - top
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((-left, -top), ch, font=font, fill=255)
    rows = []
    for y in range(h):
        row = bytearray()
        for x in range(0, w, 2):
            a = img.getpixel((x, y)) * 15 // 255
            b = img.getpixel((x + 1, y)) * 15 // 255 if x + 1 < w else 0
            row.append((a << 4) | b)
        rows.append(bytes(row))
    # y is the offset from the top of the line box (ascent above the baseline).
    return dict(w=w, h=h, x=left, y=top, adv=advance, data=b"".join(rows))


def main():
    c_lines = ['// Generated by tools/gen_ui_fonts.py. Do not edit.', '', '#include "ui_font.h"', '']
    h_lines = [
        "#pragma once",
        "",
        "// Generated by tools/gen_ui_fonts.py. Do not edit.",
        "",
        "#include <stdint.h>",
        "",
        "typedef struct {",
        "    uint32_t offset;  // into bitmap",
        "    uint8_t w, h;",
        "    int8_t x, y;      // from the pen position and the top of the line box",
        "    uint8_t advance;",
        "} ui_glyph_t;",
        "",
        "typedef struct {",
        "    const char *chars;  // index of a character here is its glyph index",
        "    const ui_glyph_t *glyphs;",
        "    const uint8_t *bitmap;",
        "    uint8_t line_height;",
        "    int8_t ink_top, ink_bottom;   // rows of the line box that any glyph touches",
        "} ui_font_t;",
        "",
    ]
    for name, px, weight, chars in FONTS:
        font = load(px, weight)
        ascent, descent = font.getmetrics()
        glyphs, bitmap = [], bytearray()
        for ch in chars:
            g = rasterize(font, ch)
            g["offset"] = len(bitmap)
            bitmap += g["data"]
            glyphs.append(g)
        line_height = ascent + descent
        inked = [g for g in glyphs if g["h"]]
        ink_top = min(g["y"] for g in inked)
        ink_bottom = max(g["y"] + g["h"] for g in inked)
        escaped = "".join("\\\\" if c == "\\" else '\\"' if c == '"' else c for c in chars)
        c_lines.append(f"static const uint8_t s_{name}_bitmap[{len(bitmap)}] = {{")
        for i in range(0, len(bitmap), 24):
            c_lines.append("    " + ", ".join(f"0x{b:02x}" for b in bitmap[i : i + 24]) + ",")
        c_lines.append("};")
        c_lines.append(f"static const ui_glyph_t s_{name}_glyphs[{len(glyphs)}] = {{")
        for ch, g in zip(chars, glyphs):
            c_lines.append(
                f"    {{{g['offset']}, {g['w']}, {g['h']}, {g['x']}, {g['y']}, {g['adv']}}},  // {ch!r}"
            )
        c_lines.append("};")
        c_lines.append(
            f'const ui_font_t ui_font_{name} = {{"{escaped}", s_{name}_glyphs, s_{name}_bitmap, {line_height}, {ink_top}, {ink_bottom}}};'
        )
        c_lines.append("")
        h_lines.append(f"// Inter {px} px, weight {weight}.")
        h_lines.append(f"extern const ui_font_t ui_font_{name};")
        print(f"{name}: {len(chars)} glyphs, {len(bitmap)} bytes, line {line_height}px")
    (ROOT / "main" / "ui_font.c").write_text("\n".join(c_lines) + "\n")
    (ROOT / "main" / "ui_font.h").write_text("\n".join(h_lines) + "\n")


if __name__ == "__main__":
    main()
